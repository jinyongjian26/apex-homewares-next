import fs from 'node:fs';
import path from 'node:path';

const input = path.resolve('data/import/SHANWU-Kitchen-Appliances-Import.json');
const output = path.resolve('src/data/kitchen-catalog-products.generated.ts');
const rows = JSON.parse(fs.readFileSync(input, 'utf8'));

const products = rows.map((row) => ({
  slug: row.slug,
  name: `SHANWU ${row.product_name_original} ${row.model_original}`,
  category: 'Kitchen',
  image: row.image_path,
  description: `SHANWU ${row.product_name_original}. Model ${row.model_original}.`,
  moq: '待补充',
  price: 'Wholesale price on request',
  highlights: row.specifications_original,
  specs: [
    {label: 'Brand', value: 'SHANWU'},
    {label: 'Model', value: row.model_original},
    {label: 'Product name', value: row.product_name_original},
    ...row.specifications_original.map((value, i) => ({label: `Specification ${i + 1}`, value})),
    ...(row.voltage_hertz_power_original ? [{label: 'Voltage / Hertz / Power', value: row.voltage_hertz_power_original}] : []),
    ...(row.product_size_original ? [{label: 'Product size', value: row.product_size_original}] : []),
    ...(row.packing_information_original ? [{label: 'Packing information', value: row.packing_information_original}] : []),
    ...row.loading_quantity_original.map((value, i) => ({label: `Loading quantity ${i + 1}`, value})),
    {label: 'Company', value: '宁波山雾科技有限公司'},
  ],
}));

const source = `// Generated by scripts/import-kitchen-catalog.mjs. Do not edit manually.\nimport type {Product} from './products';\n\nexport const kitchenCatalogProducts: Product[] = ${JSON.stringify(products, null, 2)};\n`;
fs.writeFileSync(output, source, 'utf8');
console.log(`Generated ${products.length} Kitchen products -> ${output}`);
