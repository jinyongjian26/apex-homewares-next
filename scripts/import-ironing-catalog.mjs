import fs from 'node:fs';
import path from 'node:path';

const rows = JSON.parse(fs.readFileSync(path.resolve('data/import/SHANWU-Ironing-Equipment-Import.json'), 'utf8'));
const specsFor = (row) => {
  const pairs = [
    ['Brand', 'SHANWU'], ['Model', row.model_original], ['Product name', row.product_name_original],
    ...row.specifications_original.map((value, i) => [`Specification ${i + 1}`, value]),
    ['Power', row.power_original], ['Voltage', row.voltage_original], ['Frequency', row.frequency_original],
    ['Water tank capacity', row.water_tank_capacity_original], ['Unit size', row.unit_size_original],
    ['Soleplate size', row.soleplate_size_original], ['Burst of steam rate', row.burst_steam_rate_original],
    ['Spray rate', row.spray_rate_original], ['Continuous steam rate', row.continuous_steam_rate_original],
    ['Water tank provides continuous steam', row.continuous_steam_duration_original], ['Steam ready time', row.steam_ready_time_original],
    ['Packing details as follows', row.packing_details_original], ['Giftbox Size', row.giftbox_size_original],
    ['Carton Meas.', row.carton_measurement_original], ['G.W./N.W.', row.gross_net_weight_original],
    ...row.loading_quantity_original.map((value, i) => [`Loading quantity ${i + 1}`, value]),
    ['Company', '宁波山雾科技有限公司'],
  ];
  return pairs.filter(([, value]) => value !== undefined && value !== '');
};
const products = rows.map((row) => ({
  slug: row.slug,
  name: `SHANWU ${row.product_name_original} ${row.model_original}`,
  category: 'Home',
  image: row.image_path,
  description: `SHANWU ${row.product_name_original}. Model ${row.model_original}.`,
  moq: '待补充',
  price: 'Wholesale price on request',
  highlights: row.specifications_original,
  specs: specsFor(row).map(([label, value]) => ({label, value})),
}));
const source = `// Generated by scripts/import-ironing-catalog.mjs. Do not edit manually.\nimport type {Product} from './products';\n\nexport const ironingCatalogProducts: Product[] = ${JSON.stringify(products, null, 2)};\n`;
fs.writeFileSync(path.resolve('src/data/ironing-catalog-products.generated.ts'), source, 'utf8');
console.log(`Generated ${products.length} Ironing Equipment products`);
